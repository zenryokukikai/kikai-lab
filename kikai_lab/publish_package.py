def write_package(plan: PublishPlan, out_dir: Path) -> dict[str, Any]:
    """パッケージをディスクへ。既存で空でなければ拒否する (上書きしない)。"""
    if out_dir.exists() and any(out_dir.iterdir()):
        raise OperationError(
            "publish.output_exists",
            f"publish output directory is not empty: {out_dir}",
            {"out_dir": str(out_dir)},
        )
    out_dir.mkdir(parents=True, exist_ok=True)
    bundles_dir = out_dir / PACKAGE_BUNDLE_DIR
    bundles_dir.mkdir(exist_ok=True)
    for bundle_id, bundle_root in plan.bundle_roots.items():
        shutil.copytree(bundle_root, bundles_dir / bundle_id)
    run_sh = out_dir / "run.sh"
    run_sh.write_text(render_run_sh(plan), encoding="utf-8")
    run_sh.chmod(0o755)
    (out_dir / "env.example").write_text(render_env_example(plan), encoding="utf-8")
    (out_dir / "README.md").write_text(render_readme(plan), encoding="utf-8")
    return {
        "publish_name": plan.name,
        "out_dir": str(out_dir),
        "operations_total": len(plan.ops),
        "operations_published": len(plan.translated),
        "operations_skipped": [
            {
                "index": op.index,
                "operation": op.operation,
                "adapter": op.adapter,
                "reason": op.skipped_reason,
            }
            for op in plan.skipped
        ],
        "bundles": sorted(plan.bundle_roots),
        "variables": [spec.name for spec in plan.variables],
    }

